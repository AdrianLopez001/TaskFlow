package com.taskflow.model;

/**
 * ENUM PARA PRIORIDADE DA TAREFA (TaskPriority)
 * 
 * Por que usar Enums?
 * Classifica a urgência da tarefa de forma tipada (LOW, MEDIUM, HIGH). 
 * Ajuda na ordenação e filtragem das tarefas de forma padronizada.
 */
public enum TaskPriority {
    LOW,
    MEDIUM,
    HIGH
}
